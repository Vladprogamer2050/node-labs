'use strict';

const fs = require('fs');
const path = require('path');
const config = require('../config');
const { CliError } = require('../utils/errors');
const { localDate, localTime, formatBytes } = require('../utils/format');

const REPORT_TYPES = ['html', 'pdf', 'json', 'csv'];

function reportRows() {
  return [
    ['Лабораторная работа', `№${config.lab}`],
    ['Студент', config.student.fullName],
    ['Группа', config.student.group],
    ['Вариант', String(config.variant)],
    ['Дата', localDate()],
    ['Время', localTime()],
  ];
}

function buildHtml() {
  const rows = reportRows()
    .map(([key, value]) => `        <tr><th>${key}</th><td>${value}</td></tr>`)
    .join('\n');

  return `<!DOCTYPE html>
<html lang="ru">
<head>
  <meta charset="utf-8">
  <title>Отчёт — лабораторная работа №${config.lab}</title>
  <style>
    body { font-family: "Segoe UI", Arial, sans-serif; max-width: 720px; margin: 40px auto; color: #1f2933; }
    h1 { font-size: 22px; }
    table { border-collapse: collapse; width: 100%; margin-top: 24px; }
    th, td { border: 1px solid #cbd2d9; padding: 8px 12px; text-align: left; }
    th { width: 40%; background: #f5f7fa; }
    footer { margin-top: 24px; color: #7b8794; font-size: 13px; }
  </style>
</head>
<body>
  <h1>Отчёт по лабораторной работе №${config.lab}</h1>
  <p>Сгенерирован CLI-приложением <strong>${config.appName}</strong> ${localDate()} в ${localTime()}.</p>
  <table>
${rows}
  </table>
  <footer>Node.js, вариант ${config.variant}, группа ${config.student.group}</footer>
</body>
</html>
`;
}

/** Minimal but valid one-page PDF 1.4 document with a Helvetica text block. */
function buildPdf() {
  const lines = [
    `Laboratory work ${config.lab} - CLI applications`,
    '',
    `Student: Evdokimov Vladislav Evgenievich`,
    `Group: ${config.student.group}`,
    `Variant: ${config.variant}`,
    `Generated: ${localDate()} ${localTime()}`,
    '',
    'Report generated by lab17-cli.',
    'Library stack: commander, inquirer, chalk, ora, cli-progress.',
  ];

  const escape = (text) =>
    text.replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');

  const content = [
    'BT',
    '/F1 13 Tf',
    '50 790 Td',
    '18 TL',
    ...lines.map((line) => `(${escape(line)}) Tj T*`),
    'ET',
    '',
  ].join('\n');

  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] ' +
      '/Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>',
    `<< /Length ${Buffer.byteLength(content, 'latin1')} >>\nstream\n${content}endstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
  ];

  let pdf = '%PDF-1.4\n';
  const offsets = [];

  objects.forEach((body, index) => {
    offsets.push(Buffer.byteLength(pdf, 'latin1'));
    pdf += `${index + 1} 0 obj\n${body}\nendobj\n`;
  });

  const xrefOffset = Buffer.byteLength(pdf, 'latin1');
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  offsets.forEach((offset) => {
    pdf += `${String(offset).padStart(10, '0')} 00000 n \n`;
  });
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\n`;
  pdf += `startxref\n${xrefOffset}\n%%EOF\n`;

  return Buffer.from(pdf, 'latin1');
}

function buildJson() {
  const data = {
    lab: config.lab,
    app: config.appName,
    student: config.student.fullName,
    group: config.student.group,
    variant: config.variant,
    generatedAt: `${localDate()}T${localTime()}`,
    fields: Object.fromEntries(reportRows()),
  };
  return Buffer.from(`${JSON.stringify(data, null, 2)}\n`, 'utf8');
}

function buildCsv() {
  const escape = (value) =>
    /[",\r\n]/.test(value) ? `"${value.replace(/"/g, '""')}"` : value;
  const rows = [['field', 'value'], ...reportRows()].map((row) => row.map(escape).join(','));
  return Buffer.from(`${rows.join('\r\n')}\r\n`, 'utf8');
}

function assertReportType(type) {
  if (!REPORT_TYPES.includes(type)) {
    throw new CliError(
      `недопустимый тип отчёта "${type}". Допустимые значения: ${REPORT_TYPES.join(', ')}`
    );
  }
}

/**
 * Generates a report file. Type and target are validated here, so the command
 * layer stays thin and the same logic is covered by unit tests.
 */
function generateReport({ type = 'html', output, force = false, baseDir = '.' } = {}) {
  assertReportType(type);

  const displayPath = path.normalize(output || `output.${type}`).replace(/\\/g, '/');
  const absolutePath = path.resolve(baseDir, displayPath);

  if (fs.existsSync(absolutePath) && !force) {
    throw new CliError(`файл ${displayPath} уже существует`, {
      hint: 'Используйте --force для перезаписи',
    });
  }

  const builders = { html: buildHtml, pdf: buildPdf, json: buildJson, csv: buildCsv };
  const data = builders[type]();
  fs.mkdirSync(path.dirname(absolutePath), { recursive: true });
  fs.writeFileSync(absolutePath, data);

  return {
    type,
    path: displayPath,
    absolutePath,
    bytes: data.length,
    humanSize: formatBytes(data.length),
  };
}

const CONVERT_TYPES = ['html', 'json', 'csv'];

/** Converts a text file to html/json/csv for the `convert` command. */
function convertFile({ input, to = 'json', output, force = false, baseDir = '.' } = {}) {
  if (!CONVERT_TYPES.includes(to)) {
    throw new CliError(
      `недопустимый формат "${to}". Допустимые значения: ${CONVERT_TYPES.join(', ')}`
    );
  }

  const inputPath = path.resolve(baseDir, input);
  if (!fs.existsSync(inputPath)) {
    throw new CliError(`входной файл не найден: ${input}`, {
      hint: 'Проверьте путь к файлу',
    });
  }

  const text = fs.readFileSync(inputPath, 'utf8');
  const lines = text.split(/\r?\n/);
  const displayPath = path.normalize(output || `${path.basename(input, path.extname(input))}.${to}`);
  const absolutePath = path.resolve(baseDir, displayPath);

  if (fs.existsSync(absolutePath) && !force) {
    throw new CliError(`файл ${displayPath} уже существует`, {
      hint: 'Используйте --force для перезаписи',
    });
  }

  let data;
  if (to === 'json') {
    data = JSON.stringify(
      { source: input, bytes: Buffer.byteLength(text, 'utf8'), lines: lines.length, content: text },
      null,
      2
    );
  } else if (to === 'csv') {
    const escape = (value) =>
      /[",\r\n]/.test(value) ? `"${value.replace(/"/g, '""')}"` : value;
    data = ['line,text', ...lines.map((line, index) => `${index + 1},${escape(line)}`)].join('\r\n');
  } else {
    const escaped = text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
    data = `<!DOCTYPE html>\n<html lang="ru">\n<head><meta charset="utf-8"><title>${input}</title></head>\n<body>\n<pre>${escaped}</pre>\n</body>\n</html>\n`;
  }

  fs.mkdirSync(path.dirname(absolutePath), { recursive: true });
  fs.writeFileSync(absolutePath, data, 'utf8');

  return { path: displayPath, absolutePath, bytes: Buffer.byteLength(data, 'utf8'), to };
}

module.exports = {
  REPORT_TYPES,
  CONVERT_TYPES,
  assertReportType,
  generateReport,
  convertFile,
  buildPdf,
  buildHtml,
};
