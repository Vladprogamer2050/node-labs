'use strict';

const fs = require('fs');
const path = require('path');
const { execFileSync, spawnSync } = require('child_process');
const { CliError } = require('../utils/errors');
const { readConfig, readProjectPackage } = require('./config-service');
const { localDate, localTime, formatBytes } = require('../utils/format');

const PROJECT_NAME = /^[a-z0-9][a-z0-9._-]*$/i;

function validateProjectName(name) {
  const value = String(name || '').trim();
  if (!value) {
    throw new CliError('не указано название проекта', { hint: 'Используйте --name <name>' });
  }
  if (!PROJECT_NAME.test(value)) {
    throw new CliError(`недопустимое название проекта "${value}"`, {
      hint: 'Разрешены латинские буквы, цифры, дефис, точка и подчёркивание',
    });
  }
  return value;
}

function writeProjectFile(root, relative, content) {
  const absolute = path.join(root, relative);
  fs.mkdirSync(path.dirname(absolute), { recursive: true });
  fs.writeFileSync(absolute, content, 'utf8');
  return relative.replace(/\\/g, '/');
}

/**
 * Creates a real, runnable project skeleton: package.json, sources, a test
 * file and optional tooling configuration. Nothing is downloaded.
 */
function initProject({ name, type, options = [], git = false, token = null, baseDir = '.' } = {}) {
  const projectName = validateProjectName(name);
  const target = path.resolve(baseDir, projectName);

  if (fs.existsSync(target) && fs.readdirSync(target).length > 0) {
    throw new CliError(`папка "${projectName}" уже существует и не пуста`, {
      hint: 'Удалите её или выберите другое название',
    });
  }

  fs.mkdirSync(target, { recursive: true });
  const created = [];
  const useJest = options.includes('jest');

  const pkg = {
    name: projectName,
    version: '0.1.0',
    description: `${type} project generated by lab17-cli`,
    main: 'src/index.js',
    scripts: {
      start: 'node src/index.js',
      test: useJest ? 'jest' : 'node --test',
    },
    license: 'MIT',
  };
  if (useJest) pkg.devDependencies = { jest: '29.7.0' };

  created.push(writeProjectFile(target, 'package.json', `${JSON.stringify(pkg, null, 2)}\n`));

  created.push(
    writeProjectFile(
      target,
      'config.json',
      `${JSON.stringify({ name: projectName, type, entry: 'src/index.js', build: { outDir: 'dist' } }, null, 2)}\n`
    )
  );

  created.push(
    writeProjectFile(
      target,
      'src/greeting.js',
      [
        "'use strict';",
        '',
        'function greeting(name) {',
        '  return `Hello from ${name}!`;',
        '}',
        '',
        'module.exports = { greeting };',
        '',
      ].join('\n')
    )
  );

  created.push(
    writeProjectFile(
      target,
      'src/index.js',
      [
        "'use strict';",
        '',
        "const { greeting } = require('./greeting');",
        '',
        `console.log(greeting('${projectName}'));`,
        '',
      ].join('\n')
    )
  );

  const testFile = useJest
    ? [
        "'use strict';",
        '',
        "const { greeting } = require('../src/greeting');",
        '',
        "test('greeting contains the project name', () => {",
        `  expect(greeting('${projectName}')).toContain('${projectName}');`,
        '});',
        '',
        "test('greeting starts with Hello', () => {",
        "  expect(greeting('demo').startsWith('Hello')).toBe(true);",
        '});',
        '',
      ].join('\n')
    : [
        "'use strict';",
        '',
        "const test = require('node:test');",
        "const assert = require('node:assert');",
        "const { greeting } = require('../src/greeting');",
        '',
        "test('greeting contains the project name', () => {",
        `  assert.ok(greeting('${projectName}').includes('${projectName}'));`,
        '});',
        '',
        "test('greeting starts with Hello', () => {",
        "  assert.ok(greeting('demo').startsWith('Hello'));",
        '});',
        '',
        "test('greeting is a string', () => {",
        "  assert.strictEqual(typeof greeting('demo'), 'string');",
        '});',
        '',
        "test('greeting ends with an exclamation mark', () => {",
        "  assert.ok(greeting('demo').endsWith('!'));",
        '});',
        '',
      ].join('\n');
  created.push(writeProjectFile(target, 'test/app.test.js', testFile));

  created.push(
    writeProjectFile(
      target,
      'README.md',
      [
        `# ${projectName}`,
        '',
        `Project generated by lab17-cli (type: ${type}).`,
        '',
        '```bash',
        'npm start',
        'npm test',
        '```',
        '',
      ].join('\n')
    )
  );

  created.push(
    writeProjectFile(
      target,
      '.gitignore',
      ['node_modules/', 'dist/', 'coverage/', '*.log', '.env', ''].join('\n')
    )
  );

  if (options.includes('typescript')) {
    created.push(
      writeProjectFile(
        target,
        'tsconfig.json',
        `${JSON.stringify(
          {
            compilerOptions: {
              target: 'ES2022',
              module: 'commonjs',
              strict: true,
              outDir: 'dist',
              rootDir: 'src',
            },
            include: ['src/**/*.ts'],
          },
          null,
          2
        )}\n`
      )
    );
    created.push(
      writeProjectFile(
        target,
        'src/types.ts',
        [
          'export interface ProjectInfo {',
          '  name: string;',
          "  type: 'web' | 'cli' | 'library' | 'microservice';",
          '}',
          '',
        ].join('\n')
      )
    );
  }

  if (options.includes('eslint')) {
    created.push(
      writeProjectFile(
        target,
        '.eslintrc.json',
        `${JSON.stringify({ env: { node: true, es2022: true }, extends: 'eslint:recommended' }, null, 2)}\n`
      )
    );
  }

  if (options.includes('prettier')) {
    created.push(
      writeProjectFile(
        target,
        '.prettierrc',
        `${JSON.stringify({ semi: true, singleQuote: true, printWidth: 100 }, null, 2)}\n`
      )
    );
  }

  if (git) {
    try {
      execFileSync('git', ['init', '--quiet'], { cwd: target, stdio: 'ignore' });
      created.push('.git/');
    } catch (error) {
      throw new CliError('не удалось инициализировать Git-репозиторий', {
        hint: 'Проверьте, что git установлен и доступен в PATH',
      });
    }
  }

  return { dir: target, name: projectName, type, options, git, token, files: created };
}

function collectSources(root) {
  const sources = [];
  const walk = (directory) => {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true }).sort((a, b) =>
      a.name.localeCompare(b.name)
    )) {
      const absolute = path.join(directory, entry.name);
      if (entry.isDirectory()) walk(absolute);
      else if (entry.isFile() && entry.name.endsWith('.js')) {
        sources.push(path.relative(root, absolute).replace(/\\/g, '/'));
      }
    }
  };
  walk(root);
  return sources;
}

function toPosix(value) {
  return value.replace(/\\/g, '/');
}

/**
 * Builds a self-contained CommonJS bundle: every source module is wrapped in a
 * factory with its own `require`, so the single output file really runs.
 */
function createBundle({ pkg, entry, sources, srcRoot, builtAt }) {
  const entryDir = path.posix.dirname(toPosix(entry));
  const moduleId = (file) => path.posix.normalize(path.posix.join(entryDir, file));
  const entryId = moduleId(path.posix.basename(toPosix(entry)));

  const definitions = sources
    .map((file) => {
      const code = fs
        .readFileSync(path.resolve(srcRoot, file), 'utf8')
        .replace(/^#!.*\r?\n/, '');
      return `__modules[${JSON.stringify(moduleId(file))}] = function (module, exports, require) {\n${code}\n};`;
    })
    .join('\n\n');

  const header = [
    '#!/usr/bin/env node',
    `// ${pkg.name}@${pkg.version} - bundle built by lab17-cli`,
    `// date: ${builtAt}`,
    `// entry: ${entryId}`,
    "'use strict';",
    "const __path = require('path');",
    'const __modules = {};',
    'const __cache = {};',
    '',
  ].join('\n');

  const runtime = [
    'function __resolve(from, request) {',
    "  if (request.charAt(0) !== '.') return null;",
    '  const target = __path.posix.normalize(__path.posix.join(__path.posix.dirname(from), request));',
    "  const candidates = [target, target + '.js', target + '/index.js'];",
    '  for (let index = 0; index < candidates.length; index += 1) {',
    '    if (__modules[candidates[index]]) return candidates[index];',
    '  }',
    '  return null;',
    '}',
    '',
    'function __require(from, request) {',
    '  const resolved = __resolve(from, request);',
    "  if (!resolved) return require(request);",
    '  if (__cache[resolved]) return __cache[resolved].exports;',
    '  const module = { exports: {} };',
    '  __cache[resolved] = module;',
    '  __modules[resolved](module, module.exports, function (child) {',
    '    return __require(resolved, child);',
    '  });',
    '  return module.exports;',
    '}',
    '',
    `__require(${JSON.stringify(entryId)}, ${JSON.stringify(`./${path.posix.basename(entryId)}`)});`,
    '',
  ].join('\n');

  return `${header}${definitions}\n\n${runtime}`;
}

/**
 * Builds the project: bundles the sources into a single runnable file in dist/.
 * With dryRun nothing is written, which the integration tests rely on.
 */
function buildProject({ configPath = 'config.json', baseDir = '.', outDir = 'dist', dryRun = false } = {}) {
  const config = readConfig(configPath, baseDir);
  const pkg = readProjectPackage(baseDir);
  const entry = config.entry || pkg.main || 'src/index.js';
  const entryPath = path.resolve(baseDir, entry);

  if (!fs.existsSync(entryPath)) {
    throw new CliError(`точка входа не найдена: ${entry}`, {
      hint: 'Проверьте поле entry в config.json',
    });
  }

  const srcRoot = path.resolve(baseDir, path.dirname(entry));
  const sources = collectSources(srcRoot);
  const output = path.join(outDir, `${pkg.name}.js`).replace(/\\/g, '/');

  if (dryRun) {
    return { dryRun: true, entry, output, sources, bytes: 0 };
  }

  const bundle = createBundle({
    pkg,
    entry,
    sources,
    srcRoot,
    builtAt: `${localDate()} ${localTime()}`,
  });

  const absoluteOutput = path.resolve(baseDir, output);
  fs.mkdirSync(path.dirname(absoluteOutput), { recursive: true });
  fs.writeFileSync(absoluteOutput, bundle, 'utf8');

  return {
    dryRun: false,
    entry,
    output,
    sources,
    bytes: Buffer.byteLength(bundle, 'utf8'),
  };
}

/** Parses TAP (node --test), the Node 24 spec reporter and Jest summaries. */
function parseTestSummary(text) {
  const tapPass = text.match(/^# pass (\d+)$/m) || text.match(/^ℹ pass (\d+)$/m);
  if (tapPass) {
    const passed = Number(tapPass[1]);
    const failedMatch = text.match(/^# fail (\d+)$/m) || text.match(/^ℹ fail (\d+)$/m);
    const testsMatch = text.match(/^# tests (\d+)$/m) || text.match(/^ℹ tests (\d+)$/m);
    const failed = failedMatch ? Number(failedMatch[1]) : 0;
    return {
      parsed: true,
      passed,
      failed,
      total: testsMatch ? Number(testsMatch[1]) : passed + failed,
    };
  }

  const jestPassed = text.match(/Tests:.*?(\d+) passed/);
  const jestFailed = text.match(/Tests:.*?(\d+) failed/);
  const jestTotal = text.match(/(\d+) total/);
  if (jestPassed || jestFailed) {
    const passed = jestPassed ? Number(jestPassed[1]) : 0;
    const failed = jestFailed ? Number(jestFailed[1]) : 0;
    return { parsed: true, passed, failed, total: jestTotal ? Number(jestTotal[1]) : passed + failed };
  }

  return { parsed: false, passed: 0, failed: 0, total: 0 };
}

/** Runs `npm test` inside the generated project and parses the summary. */
function runProjectTests({ baseDir = '.' } = {}) {
  readProjectPackage(baseDir);

  const result = spawnSync('npm test', {
    cwd: path.resolve(baseDir),
    shell: true,
    encoding: 'utf8',
    env: { ...process.env, CI: 'true' },
    timeout: 120000,
  });

  const output = `${result.stdout || ''}${result.stderr || ''}`;
  return {
    code: result.status === null ? 1 : result.status,
    output,
    ...parseTestSummary(output),
  };
}

module.exports = {
  validateProjectName,
  initProject,
  buildProject,
  collectSources,
  parseTestSummary,
  runProjectTests,
};
